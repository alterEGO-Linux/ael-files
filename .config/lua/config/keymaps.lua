local map = vim.keymap.set
local f = require('config.functions')
map('i', ',,', '<Esc>')
map('x', ',,', '<Esc>')
map({ 'n', 'i' }, '<C-s>', function() vim.cmd.write() end, { desc = 'Save file' })
map('n', '<leader>ev', '<cmd>tabedit $MYVIMRC<cr>', { desc = 'Edit config' })
map('n', '<leader>so', '<cmd>source $MYVIMRC<cr>', { desc = 'Reload entry config' })
map('n', '<leader>w', function() vim.wo.wrap = not vim.wo.wrap end, { desc = 'Toggle wrap' })
map('n', '<leader>ln', function() vim.wo.number = not vim.wo.number; vim.wo.relativenumber = not vim.wo.relativenumber end)
map('n', '<F3>', function() vim.o.hlsearch = not vim.o.hlsearch end)
map('n', '<leader>cs', '<cmd>nohlsearch<cr>')
map('n', '<F4>', f.toggle_netrw)
map('n', '<F5>', function() vim.wo.spell = not vim.wo.spell; vim.opt_local.spelllang = 'en_us' end)
map('n', '<leader>sl', f.toggle_spell_language)
map('n', '<leader>er', f.ranger)
map('n', '<leader>b', f.toggle_bionic)
map('n', '<leader>hl', function() vim.fn.matchadd('LineHighlight', '\\%' .. vim.fn.line('.') .. 'l') end)
map('n', '<leader>hc', function() vim.fn.clearmatches() end)
map('n', '<leader>k', function() vim.cmd('Man ' .. vim.fn.expand('<cword>')) end)
map('n', '<leader>hp', function() vim.cmd('terminal pydoc ' .. vim.fn.shellescape(vim.fn.expand('<cword>'))) end)
map('n', '<F12>', function() vim.api.nvim_put({ os.date('!%Y-%m-%d %H:%M:%S UTC') }, 'c', true, true) end)
map('n', '<F9>', function() vim.api.nvim_put({ os.date('!%Y%m%d%H%M') }, 'c', true, true) end)
map('n', '<leader>mv', function()
  local file = vim.fn.expand('%:p')
  vim.cmd('silent !bash ' .. vim.fn.shellescape(vim.fn.expand('~/main/dev/mdviewer/mdviewer.bash')) .. ' ' .. vim.fn.shellescape(file))
  vim.cmd.redraw()
end)
map('x', '<leader>64', function()
  local selected = vim.fn.getreg('"')
  vim.cmd('normal! y')
  local decoded = vim.fn.system('base64 --decode', vim.fn.getreg('"'))
  if vim.v.shell_error == 0 then vim.fn.setreg('"', decoded); vim.cmd('normal! gvP') else vim.fn.setreg('"', selected); vim.notify('Invalid base64', vim.log.levels.ERROR) end
end)
map('n', '<C-u>', 'viwUea')
map('i', '<C-u>', '<Esc>viwUea')
map('n', '<C-l>', 'viwu')
map('i', '<C-l>', '<Esc>viwu')
-- Clipboard is handled by unnamedplus; retain optional F7 mappings.
map('x', '<F7>', '"+y')
map('n', '<S-F7>', '"+p')
for lhs, rhs in pairs({ ['"<Tab>'] = '""<Left>', ["'<Tab>"] = "''<Left>", ['(<Tab>'] = '()<Left>', ['[<Tab>'] = '[]<Left>', ['{<Tab>'] = '{}<Left>' }) do
  map('i', lhs, rhs)
end
map('i', '{<CR>', '{<CR>}<Esc>O')
map('i', '{;<CR>', '{<CR>};<Esc>O')
map('i', 'lorem<Tab>', 'Lorem ipsum dolor sit amet, consectetur adipiscing elit.')
-- Toggle comments with Neovim's native gc operator (0.10+); leader-c convenience.
map('n', '<leader>c', 'gcc', { remap = true })
map('x', '<leader>c', 'gc', { remap = true })
